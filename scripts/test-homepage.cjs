const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const exported = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/homepage-settings.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, { exports: exported, require });
const { applyHomepageSettings, homepageSchema } = exported;
const p = { id: '11111111-1111-4111-8111-111111111111', name: 'Example', is_active: true, variants: [{ image_urls: ['https://example.com/a.jpg', 'https://example.com/b.jpg'], price_override: 123 }] };
const choice = { productId: p.id, image: 'https://example.com/b.jpg' };
const config = { covers: { sarees: choice }, featured: [choice] };
assert.equal(homepageSchema.safeParse(config).success, true);
assert.equal(homepageSchema.safeParse({ ...config, featured: [choice, choice] }).success, false);
const output = applyHomepageSettings([{ slug: 'sarees', image_url: 'original' }], [p], [p], config);
assert.equal(output.categories[0].image_url, choice.image);
assert.equal(output.products[0].variants[0].image_urls[0], choice.image);
assert.equal(output.products[0].variants[0].price_override, 123);
assert.equal(p.variants[0].image_urls[0], 'https://example.com/a.jpg');
assert.equal(applyHomepageSettings([{ slug: 'sarees', image_url: 'original' }], [], [], config).categories[0].image_url, 'original');
assert.equal(applyHomepageSettings([], [], [{ ...p, is_active: false }], config).products.length, 0);
console.log('Homepage selection, validation, fallback and non-mutation tests passed.');
